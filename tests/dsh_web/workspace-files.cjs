const assert = require('node:assert/strict')
const { chromium } = require(process.env.DSH_PLAYWRIGHT_CORE || '../../AIbertAI/code/app/node_modules/playwright-core')

// Start TestDSHWebFixture with DSH_WEB_SERVE=1 and DSH_WEB_FILES=1.
async function run() {
  const base = process.env.DSH_WEB_BASE || 'http://127.0.0.1:18767'
  const browser = await chromium.launch({ executablePath: process.env.DSH_CHROME, headless: true })
  const context = await browser.newContext({ locale: 'zh-CN', viewport: { width: 1760, height: 980 } })
  const page = await context.newPage()
  const errors = []
  const remoteRequests = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => {
    if (request.url().startsWith('https://remote-image.invalid/')) remoteRequests.push(request.url())
  })
  try {
    const { sessionId } = await (await context.request.get(base + '/fixture')).json()
    const url = base + '/sessions/' + sessionId
    await page.goto(url)
    const login = page.getByRole('button', { name: '登录', exact: true })
    const tools = page.getByRole('button', { name: /会话的工具/ })
    await login.or(tools).first().waitFor()
    if (await login.isVisible()) {
      await page.locator('input').first().fill(base)
      await login.click()
      await page.waitForURL(address => address.pathname !== '/login')
      await page.goto(url)
    }
    const reader = page.locator('.files-reader')
    const tree = page.locator('[data-files-page]')
    const tabs = page.locator('.dsh-employee-file-tabs [role="tab"]')
    const tab = name => tabs.filter({ hasText: name })
    const active = name => tab(name).evaluate(element => element.getAttribute('aria-selected') === 'true')
    const close = async name => {
      await tab(name).hover()
      await tab(name).locator('[data-dockkit-tab-close]').click()
    }
    const guideLink = page.getByRole('button', { name: '查看开发指南', exact: true })
    const delivery = page.locator('[data-presented-file] button').first()
    const markdown = page.locator('[data-document-markdown]')
    const toggle = page.locator('[data-files-navigator-toggle]')
    await guideLink.click()
    await markdown.getByRole('heading', { name: '工作区指南' }).waitFor()
    await markdown.locator('[data-document-frontmatter]').waitFor()
    assert.equal(await tree.isVisible(), false)
    assert.equal(await active('README.md'), true)
    assert.equal(await reader.locator('[data-textpreview-path]').innerText(), '指南/README.md')
    await delivery.click()
    await page.locator('[data-code-preview]').getByText('const accepted = true;', { exact: false }).last().waitFor()
    assert.equal(await tabs.count(), 2)
    assert.equal(await active('example.js'), true)
    assert.equal(await tree.isVisible(), false)
    await tab('README.md').click()
    await markdown.getByRole('button', { name: '同目录说明' }).click()
    await page.locator('[data-textpreview-plain]').getByText('同目录定位成功。').waitFor()
    await page.reload()
    await page.locator('[data-textpreview-plain]').getByText('同目录定位成功。').waitFor()
    assert.equal(await active('note.txt'), true)
    assert.equal(await tabs.count(), 3)
    await delivery.click()
    assert.equal(await tabs.count(), 3, 'the same delivery reuses a tab')
    await toggle.click()
    await tree.waitFor()
    const scope = tree.getByRole('button', { name: '文件范围' })
    await scope.focus()
    await page.keyboard.press('ArrowDown')
    const scopeMenu = page.getByRole('menu')
    await scopeMenu.getByRole('menuitem', { name: '本次对话改动' }).waitFor()
    await page.keyboard.press('Home')
    await page.keyboard.press('ArrowDown')
    await page.keyboard.press('Enter')
    await tree.getByRole('button', { name: '文件范围' }).filter({ hasText: '本次对话改动' }).waitFor()
    await scope.click()
    await scopeMenu.getByRole('menuitem', { name: '工作区文件' }).click()
    assert.equal(await tree.locator('select').count(), 0)
    await toggle.click()
    await tree.waitFor({ state: 'hidden' })
    await page.setViewportSize({ width: 1050, height: 800 })
    await toggle.click()
    await tree.waitFor()
    await toggle.click()
    await tree.waitFor({ state: 'hidden' })
    await page.setViewportSize({ width: 1760, height: 980 })
    await tab('README.md').click()
    await close('README.md')
    await page.locator('[data-code-preview]').waitFor()
    assert.equal(await active('example.js'), true)
    await close('note.txt')
    assert.equal(await active('example.js'), true)
    await close('example.js')
    await tree.waitFor()
    assert.equal(await tabs.count(), 0)
    assert.equal(await reader.count(), 0)
    const directory = tree.getByRole('treeitem', { name: '指南', exact: true })
    if (await directory.getAttribute('aria-expanded') !== 'true') await directory.click()
    await tree.getByRole('treeitem', { name: 'README.md', exact: true }).click()
    await markdown.getByRole('heading', { name: '工作区指南' }).waitFor()
    await page.locator('[data-dockkit-add-tab]').click()
    await tree.waitFor()
    await tab('README.md').click()
    await markdown.getByRole('heading', { name: '工作区指南' }).waitFor()
    await toggle.click()
    await tree.waitFor()
    const htmlFile = tree.getByRole('treeitem', { name: 'viewer.html', exact: true })
    if (!(await htmlFile.isVisible())) await directory.click()
    await htmlFile.click()
    const menu = reader.getByRole('button', { name: '打开方式', exact: true })
    const choose = async name => {
      await menu.click()
      await page.getByRole('menuitem', { name, exact: true }).click()
    }
    const html = reader.frameLocator('iframe[data-html-preview]')
    await html.getByRole('heading', { name: '查看器验收' }).waitFor()
    assert.equal(await menu.textContent(), 'HTML')
    assert.equal(await reader.locator('iframe[data-html-preview]').getAttribute('sandbox'), '')
    assert.equal(await reader.locator('.workspace-view-modes').count(), 0)
    await menu.focus()
    await page.keyboard.press('ArrowDown')
    for (const name of ['HTML', '交互式预览', '代码', '纯文本']) {
      await page.getByRole('menuitem', { name, exact: true }).waitFor()
    }
    await page.getByRole('menuitem', { name: '交互式预览', exact: true }).click()
    const interactive = reader.frameLocator('iframe[sandbox="allow-scripts"]')
    await interactive.getByRole('button', { name: '运行示例' }).press('Enter')
    await interactive.getByText('交互已运行', { exact: true }).waitFor()
    await choose('代码')
    await reader.locator('[data-code-preview]').getByText(/查看器验收/).first().waitFor()
    const wrap = reader.getByRole('button', { name: '自动换行', exact: true })
    await wrap.click()
    await reader.locator('[data-code-preview][data-wrap="true"]').waitFor()
    await choose('纯文本')
    await reader.locator('[data-textpreview-plain]').waitFor()
    await page.reload()
    await reader.locator('[data-textpreview-plain]').waitFor()
    assert.equal(await menu.textContent(), '纯文本')
    assert.equal(await wrap.getAttribute('aria-pressed'), 'true')
    await reader.getByRole('button', { name: '重新读取文件' }).click()
    await reader.locator('[data-textpreview-plain]').getByText(/查看器验收/).first().waitFor()
    await choose('HTML')
    await html.getByRole('heading', { name: '查看器验收' }).waitFor()
    const openNeighbor = async name => {
      if (!(await tree.isVisible())) await toggle.click()
      const row = tree.getByRole('treeitem', { name, exact: true })
      if (!(await row.isVisible())) await directory.click()
      await row.click()
    }
    await openNeighbor('图示.svg')
    const image = reader.locator('[data-image-preview] img')
    await image.waitFor()
    await image.evaluate(element => element.decode())
    const zoom = reader.locator('[data-document-zoom-controls]')
    await zoom.getByRole('button', { name: '放大', exact: true }).focus()
    await zoom.getByRole('button', { name: '放大', exact: true }).press('Enter')
    await reader.locator('[data-document-zoom-mode="fixed"]').waitFor()
    await openNeighbor('开支.xlsx')
    const spreadsheet = reader.locator('[data-excel-preview]')
    await spreadsheet.getByText('预算', { exact: true }).waitFor()
    const secondSheet = spreadsheet.getByText('实际支出', { exact: true })
    await secondSheet.click()
    await spreadsheet.locator('.luckysheet-sheets-item-active').getByText('实际支出', { exact: true }).waitFor()
    await openNeighbor('销售.csv')
    await spreadsheet.locator('canvas').first().waitFor()
    assert.deepEqual(errors, [])
    assert.deepEqual(remoteRequests, [])
    console.log('Verified file navigation, HTML modes, native Markdown/code, persistent wrap, image zoom, XLSX sheet selection, CSV and session restore.')
  } finally {
    await context.request.post(base + '/fixture/finish').catch(() => {})
    await browser.close()
  }
}
run().catch(error => { console.error(error); process.exitCode = 1 })
